expect(rplTablePanel, /eventLabels[\s\S]*landing: '登陆站'[\s\S]*repeater: '放大器'[\s\S]*waypoint: '路径点'[\s\S]*'Alter Course': '转向点'/, 'RPL event values must be localized instead of exposing internal English enums')
expect(rplTablePanel, /normalizeMeaningfulText\(record\.additionalFeatures\)[\s\S]*normalizeMeaningfulText\(record\.remarks\)/, 'RPL placeholder features must fall back to meaningful remarks')
